namespace Fußball_2
{
    public class Trainer
    {
        // Attribute von Trainern
        public string Name;
        public int Alter;
        public double Erfahrung;
        
        // Konstruktor
        public Trainer(string name, int alter, double erfahrung)
        {
            Name = name;
            Alter = alter;
            Erfahrung = erfahrung;
        }
    }
}